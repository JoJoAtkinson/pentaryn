"""The generated "Module APIs (`game.pentaryn`)" index in context/foundry/README.md.

python-tooling-36 + mcp-fork-20 + W7: one table, generated, never hand-kept. An LLM that
lands in the Foundry domain root needs to know which namespace is which module before it
spends eval-js calls on `Object.keys(game.pentaryn)` — and namespaces that do not match
the module id (`rules` is pentaryn-lookup, `chain` is senses) cannot be guessed.

Sources, all read-only:

* each `foundry/module/*/module.json` — id, title, version, `flags.pentaryn.namespace`;
* the module's own code, for the namespace(s) it publishes while its manifest has no
  `namespace` flag (the shapes the modules use: ``game.pentaryn = { ...current, ns: …}``,
  ``game.pentaryn.ns = …``, ``publishNamespace("ns", …)``);
* `test/golden/describe.json` when the module has one (blueprint modules) — its method
  paths are the API column; otherwise the column says there is no golden yet;
* `lib/kit.lock.json` (tier) and `test/run.mjs` (suite) via the ModuleSpec.

    python -m scripts.foundry.ops module-index          # rewrite the block
    python -m scripts.foundry.ops module-index --check  # exit 1 when it is stale

`make check-context` runs the check, so a module added, renamed or re-versioned without
regenerating fails there.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from . import config as cfg

README = cfg.REPO_ROOT / "context/foundry/README.md"
START = ("<!-- module-index:start — generated by `python -m scripts.foundry.ops module-index`; "
         "edit the modules, not this block -->")
END = "<!-- module-index:end -->"

#: kit names every blueprint module carries; not worth a column cell each
_RESERVED = {"describe", "inspect", "settings", "trace", "version", "contract", "uninstall",
             "selftest"}
_API_CELL_MAX = 8

_PUBLISH_RE = re.compile(
    r"game\.pentaryn\s*=\s*\{\s*\.\.\.\s*[\w.$]+\s*,\s*(\w+)\s*:"   # { ...current, ns: … }
    r"|game\.pentaryn\.(\w+)\s*=(?!=)"                             # game.pentaryn.ns = …
    r"|publishNamespace\(\s*[\"'](\w+)[\"']")                      # kit publish("ns", …)


def _json(path: Path) -> dict | None:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return data if isinstance(data, dict) else None


def published_namespaces(module_dir: Path) -> list[str]:
    """Namespaces the module's own code assigns under game.pentaryn (tests and lib/ excluded)."""
    found: set[str] = set()
    for f in sorted(module_dir.rglob("*.mjs")):
        parts = set(f.relative_to(module_dir).parts[:-1])
        if parts & {"test", "lib", "node_modules"}:
            continue
        try:
            text = f.read_text(encoding="utf-8")
        except OSError:
            continue
        for m in _PUBLISH_RE.finditer(text):
            found.add(next(g for g in m.groups() if g))
    return sorted(found)


def module_row(module_dir: Path) -> dict:
    """Everything the index says about one module, as data."""
    manifest = _json(module_dir / "module.json") or {}
    flags = (manifest.get("flags") or {}).get("pentaryn") or {}
    describe = _json(module_dir / "test/golden/describe.json")
    primary = ([flags["namespace"]] if flags.get("namespace")
               else [describe["namespace"]] if describe and describe.get("namespace")
               else [])
    # Plus any literal name the code publishes: an alias (senses' `chain`) has no golden of its own.
    namespaces = sorted(set(primary) | set(published_namespaces(module_dir)))
    api = None
    if describe is not None:
        api = [m["path"] for m in describe.get("methods") or []
               if isinstance(m, dict) and m.get("path") and m["path"] not in _RESERVED]
    lock = _json(module_dir / "lib/kit.lock.json")
    short = module_dir.name.removeprefix("pentaryn-")
    use_doc = cfg.REPO_ROOT / "context/foundry" / f"{short}.md"
    return {
        "id": manifest.get("id") or module_dir.name,
        "short": short,
        "title": manifest.get("title") or "",
        "version": manifest.get("version") or "?",
        "namespaces": namespaces,
        "api": api,
        "tier": flags.get("tier") or (lock or {}).get("tier") or ("full" if lock else None),
        "suite": (module_dir / "test/run.mjs").is_file(),
        "useDoc": f"{short}.md" if use_doc.is_file() else None,
        "readme": (module_dir / "README.md").is_file(),
    }


def rows(root: Path | None = None) -> list[dict]:
    root = root or cfg.MODULE_SRC_ROOT
    return [module_row(root / name) for name in cfg.module_dirs(root)]


def _api_cell(api: list[str] | None) -> str:
    if api is None:
        return "— (no describe golden yet)"
    if not api:
        return "kit members only"
    shown = ", ".join(f"`{p}`" for p in api[:_API_CELL_MAX])
    return shown + (f" … (+{len(api) - _API_CELL_MAX})" if len(api) > _API_CELL_MAX else "")


def render(root: Path | None = None) -> str:
    """The block between the markers (markers included), deterministic for --check."""
    lines = [START, "",
             "| Namespace | Module | Version | Blueprint | API (describe golden) | Docs |",
             "|---|---|---|---|---|---|"]
    for r in rows(root):
        ns = ", ".join(f"`{n}`" for n in r["namespaces"]) or "— (publishes none)"
        bp = f"{r['tier']} tier" if r["tier"] else "not migrated"
        docs = []
        if r["useDoc"]:
            docs.append(f"[`{r['useDoc']}`]({r['useDoc']})")
        if r["readme"]:
            docs.append(f"[README](../../foundry/module/{r['id']}/README.md)")
        lines.append(f"| {ns} | `{r['id']}` | {r['version']} | {bp} | {_api_cell(r['api'])} | "
                     f"{' · '.join(docs) or '—'} |")
    lines += ["", END]
    return "\n".join(lines)


def splice(text: str, block: str) -> str:
    """`text` with the marked block replaced. Raises ValueError when the markers are missing."""
    i, j = text.find(START), text.find(END)
    if i < 0 or j < i:
        raise ValueError("module-index markers not found")
    return text[:i] + block + text[j + len(END):]


def is_current(readme: Path = README, root: Path | None = None) -> bool:
    try:
        text = readme.read_text(encoding="utf-8")
        return splice(text, render(root)) == text
    except (OSError, ValueError):
        return False


def write(readme: Path = README, root: Path | None = None) -> bool:
    """Rewrite the block; True when the file changed."""
    text = readme.read_text(encoding="utf-8")
    new = splice(text, render(root))
    if new == text:
        return False
    readme.write_text(new, encoding="utf-8")
    return True


def main(check: bool = False) -> int:
    rel = README.relative_to(cfg.REPO_ROOT)
    if check:
        if is_current():
            print(f"  ✓ {rel}: module index current")
            return 0
        print(f"  ✗ {rel}: module index stale or markers missing — "
              "run: python -m scripts.foundry.ops module-index")
        return 1
    changed = write()
    print(f"  ✓ {rel}: module index {'rewritten' if changed else 'already current'}")
    return 0
